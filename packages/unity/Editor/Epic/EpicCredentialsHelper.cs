using System;
using System.IO;
using UnityEngine;

namespace Covyne.CADET.Editor.Epic
{
    /// <summary>
    /// Helper class for reading and writing Epic credentials to ~/.env_cadet_epic_credentials
    /// </summary>
    public static class EpicCredentialsHelper
    {
        private const string CREDENTIALS_FILE_NAME = ".env_cadet_epic_credentials";
        
        /// <summary>
        /// Gets the full path to the credentials file in the user's home directory
        /// </summary>
        public static string GetCredentialsFilePath()
        {
            string homeDir = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
            return Path.Combine(homeDir, CREDENTIALS_FILE_NAME);
        }
        
        /// <summary>
        /// Checks if credentials file exists
        /// </summary>
        public static bool CredentialsFileExists()
        {
            return File.Exists(GetCredentialsFilePath());
        }
        
        /// <summary>
        /// Reads credentials from the file
        /// </summary>
        public static EpicCredentials ReadCredentials()
        {
            string filePath = GetCredentialsFilePath();
            
            if (!File.Exists(filePath))
            {
                return new EpicCredentials();
            }
            
            try
            {
                string[] lines = File.ReadAllLines(filePath);
                var credentials = new EpicCredentials();
                
                foreach (string line in lines)
                {
                    string trimmedLine = line.Trim();
                    if (string.IsNullOrEmpty(trimmedLine) || trimmedLine.StartsWith("#"))
                        continue;
                    
                    // Parse KEY=VALUE format
                    int equalsIndex = trimmedLine.IndexOf('=');
                    if (equalsIndex > 0)
                    {
                        string key = trimmedLine[..equalsIndex].Trim();
                        string value = trimmedLine[(equalsIndex + 1)..].Trim();
                        
                        // Remove quotes if present
                        if (value.StartsWith("\"") && value.EndsWith("\""))
                        {
                            value = value[1..^1];
                        }
                        
                        switch (key.ToUpper())
                        {
                            case "CLIENT_ID":
                                credentials.ClientId = value;
                                break;
                            case "CLIENT_SECRET":
                                credentials.ClientSecret = value;
                                break;
                        }
                    }
                }
                
                return credentials;
            }
            catch (Exception ex)
            {
                Debug.LogError($"[CADET] Failed to read Epic credentials: {ex.Message}");
                return new EpicCredentials();
            }
        }
        
        /// <summary>
        /// Writes credentials to the file
        /// </summary>
        public static bool WriteCredentials(EpicCredentials credentials)
        {
            if (credentials == null)
            {
                Debug.LogError("[CADET] Cannot write null credentials");
                return false;
            }
            
            string filePath = GetCredentialsFilePath();
            
            try
            {
                var lines = new System.Collections.Generic.List<string>();
                lines.Add("# CADET Epic Games Store Credentials");
                lines.Add("# This file is automatically generated. Do not edit manually.");
                lines.Add("");
                
                if (!string.IsNullOrEmpty(credentials.ClientId))
                {
                    lines.Add($"CLIENT_ID={credentials.ClientId}");
                }
                
                if (!string.IsNullOrEmpty(credentials.ClientSecret))
                {
                    lines.Add($"CLIENT_SECRET={credentials.ClientSecret}");
                }
                
                // Write file with Unix line endings (LF only) to avoid bash warnings when sourcing
                File.WriteAllText(filePath, string.Join("\n", lines) + "\n");
                
                // Set file permissions to user-only (600 on Unix)
                // On Windows, this is handled by the file system
                #if UNITY_EDITOR_WIN
                // Windows doesn't need explicit permission setting
                #else
                try
                {
                    System.Diagnostics.Process.Start("chmod", $"600 \"{filePath}\"");
                }
                catch
                {
                    // Ignore if chmod fails
                }
                #endif
                
                return true;
            }
            catch (Exception ex)
            {
                Debug.LogError($"[CADET] Failed to write Epic credentials: {ex.Message}");
                return false;
            }
        }
        
        /// <summary>
        /// Deletes the credentials file
        /// </summary>
        public static bool DeleteCredentials()
        {
            string filePath = GetCredentialsFilePath();
            
            if (!File.Exists(filePath))
            {
                return true; // Already deleted
            }
            
            try
            {
                File.Delete(filePath);
                return true;
            }
            catch (Exception ex)
            {
                Debug.LogError($"[CADET] Failed to delete Epic credentials: {ex.Message}");
                return false;
            }
        }
    }
}

